"""Free fly + cameras (see V016)."""
import json
from harness import *
async def run(br,site,fx):
    t=await open_page(br,site,"camera",w=900,h=560); ok=t.ok
    await t.new_project(); await t.add_ply(fx["tilt"],1800); await t.ev("closeTool();dirty=true"); await t.wait(400)
    ok("free fly is the default",(await t.ev("S.ctrl"))=="fly")
    async def step(zm):
        await t.ev(f"resetView();zoom={zm};draw(null);KEYS={{KeyW:true}};lastKT=1000;var _a=TG.slice();stepKeys(1040);KEYS={{}};window.__d=Math.hypot(TG[0]-_a[0],TG[1]-_a[1],TG[2]-_a[2])")
        return await t.ev("window.__d")
    d1,d2,d3=await step(0.01),await step(1),await step(4)
    ok("W moves the same distance at any zoom (never slows to nothing)",abs(d1-d2)<1e-6 and abs(d2-d3)<1e-6,[d1,d2,d3])
    async def wh(zm):
        await t.ev(f"resetView();zoom={zm};draw(null)"); a=await t.ev("TG.slice()")
        await t.pg.mouse.move(450,280); await t.pg.mouse.wheel(0,-200); await t.wait(250)
        return L(sub(await t.ev("TG.slice()"),a))
    w1,w2=await wh(0.01),await wh(3)
    ok("wheel steps are the same at any zoom",abs(w1-w2)<1e-6 and w1>0.05,[w1,w2])
    eye=lambda: t.ev("(function(){var d=viewDist();return [TG[0]+Rm[2]*d,TG[1]+Rm[5]*d,TG[2]-zmNow()+Rm[8]*d]})()")
    await t.ev("resetView();SEL=null;draw(null)"); e0=await eye()
    box=await t.pg.locator("#gl").bounding_box(); cx,cy=box["x"]+box["width"]/2,box["y"]+box["height"]/2
    await t.pg.mouse.move(cx,cy); await t.pg.mouse.down()
    for s in range(14): await t.pg.mouse.move(cx+s*14,cy+s*5)
    await t.pg.mouse.up(); await t.wait(400)
    ok("left-drag looks around without moving the eye",L(sub(e0,await eye()))<1e-5)
    ok("drag right turns the view right",(await t.ev("-Rm[2]"))>0.05)
    ok("no coasting after the drag",(await t.ev("vyaw"))==0)
    for m in ["orbit","trackball","fly"]:
        await t.ev(f"setK('ctrl','{m}');orbitBy(0.2,0.1);zoomAt(0.9,450,280);panBy(10,10);KEYS={{KeyW:true}};lastKT=1000;stepKeys(1030);KEYS={{}};draw(null)")
    await t.ev("resetView()")
    await t.ev("setMode('render')"); await t.wait(400)
    ok("camera button hidden with no cameras",await t.pg.is_hidden("#camBtn"))
    await t.pg.click('[data-tool=camera]'); await t.wait(300); await t.ev("openTool('camera')"); await t.wait(200)
    await t.ev("rawTurnTo(0.5,0.2);TG=[0.2,0,0.3];dirty=true"); await t.wait(300)
    await t.pg.click('[data-act=camAdd]'); await t.wait(400)
    ok("camera added and selected",(await t.ev("cams().length"))==1 and (await t.ev("SEL&&SEL.kind"))=="camera")
    async def cam(): return json.loads(await t.ev("JSON.stringify({p:curCam().pos,R:curCam().R,d:curCam().fdist})"))
    c0=await cam()
    await t.ev("KEYS={KeyD:true,KeyS:true};lastKT=1000;for(var i=1;i<=20;i++)stepKeys(1000+i*30);KEYS={};orbitBy(0.12,0.05);draw(null)")
    nz=await t.pg.evaluate("(()=>{const o=document.getElementById('ov'),d=o.getContext('2d').getImageData(0,0,o.width,o.height).data;let n=0;for(let i=3;i<d.length;i+=4)if(d[i])n++;return n})()")
    ok("camera shape is drawn in Render",nz>50,nz)
    ok("move gizmo is available on the camera",await t.ev("!!gzGeo()"))
    await t.ev("SEL=null;dirty=true")
    pr=await t.ev("(function(){var p=projW(worldOf(curCam()));return p?[p[0],p[1]]:null})()")
    if pr:
        r=await t.ev(f"(function(){{var rr=cv.getBoundingClientRect();return tapObj({{clientX:{pr[0]}+rr.left,clientY:{pr[1]}+rr.top}})}})()")
        ok("tapping the camera shape selects it",r is True and (await t.ev("SEL&&SEL.kind"))=="camera")
    else: ok("camera is on screen to tap",False)
    await t.pg.mouse.dblclick(cx-30,cy-20); await t.wait(1200); await t.pg.mouse.wheel(0,-300); await t.wait(300)
    await t.ev("SEL=curCam();openTool('camera',true)")
    c1=await cam(); ok("moving the free view (incl. double-click) never moves the camera",L(sub(c0['p'],c1['p']))<1e-9 and L(sub(c0['R'],c1['R']))<1e-9)
    vpBefore=await t.ev("JSON.stringify({R:Rm,TG:TG,z:zoom,f:S.fov})")
    await t.pg.click('[data-act=camThru]'); await t.wait(500)
    ok("looking through the camera",(await t.ev("THRU"))==True)
    e=await eye(); ok("view eye = camera position",L(sub(e,[c1['p'][0],c1['p'][1],c1['p'][2]-1.95]))<1e-4)
    await t.ev("window.__dd=[];window.__o=drawSplats;drawSplats=function(V,Pm,w,h,tyv,dist){__dd.push(dist);return __o.apply(this,arguments)};draw(null)")
    dd=await t.ev("__dd[__dd.length-1]"); ok("depth reference = camera focus distance",abs(dd-c1['d'])<1e-3,[dd,c1['d']])
    await t.ev("KEYS={KeyW:true,KeyE:true};lastKT=1000;for(var i=1;i<=25;i++)stepKeys(1000+i*30);KEYS={};dirty=true"); await t.wait(1200)
    c2=await cam(); ok("flying in the camera moves the camera",L(sub(c2['p'],c1['p']))>0.2)
    await t.pg.click('#camBtn'); await t.wait(500)
    c3=await cam(); ok("leaving: camera stays where it was left",(await t.ev("THRU"))==False and L(sub(c3['p'],c2['p']))<1e-9)
    ok("leaving: free view comes back exactly",(await t.ev("JSON.stringify({R:Rm,TG:TG,z:zoom,f:S.fov})"))==vpBefore)
    await t.ev("draw(null)")
    chk=await t.ev("(function(){var f=camFocusPt(curCam()),V=LASTM.V;return [__dd[__dd.length-1],-(V[2]*f[0]+V[6]*f[1]+V[10]*f[2]+V[14])]})()")
    ok("depth effects measured to the camera's focus point",abs(chk[0]-chk[1])<1e-4,chk)
    await t.ev("S.fog=0.7;S.defocus=0.5;S.focus=0.5;SEL=curCam();openTool('camera',true)")
    await t.pg.click('[data-act=camThru]'); await t.wait(700); sb=await t.pg.evaluate(SNAP)
    await t.pg.click('#camBtn'); await t.wait(300)
    await t.ev("rawTurnTo(1.3,-0.2);TG=[1.3,0.4,-0.6];zoom=2.2;dirty=true;draw(null)"); await t.pg.mouse.dblclick(cx+60,cy+40); await t.wait(900)
    await t.pg.click('#camBtn'); await t.wait(900); sc=await t.pg.evaluate(SNAP)
    ok("same picture from the camera after wandering with the free view",dif(sb,sc)<20,dif(sb,sc))
    await t.pg.click('#camBtn'); await t.wait(300)
    await t.ev("startAnim(false)"); await t.wait(500); ok("Play enters the camera",(await t.ev("THRU"))==True); await t.ev("stopAnim()"); await t.pg.click('#camBtn')
    await t.ev("addCamera()"); ok("two cameras",(await t.ev("cams().length"))==2)
    await t.ev("enterThru(cams()[0]);enterThru(cams()[1])"); ok("switch camera while looking through",(await t.ev("ACAM.name"))=="Camera 2"); await t.ev("leaveThru()")
    await t.ev("enterThru(cams()[0])"); await t.ev("setMode('edit')"); await t.wait(400)
    ok("Workspace leaves the camera view",(await t.ev("THRU"))==False)
    await t.ev("setMode('render')"); await t.wait(300)
    await t.ev("while(cams().length)removeObj(cams()[0])"); await t.wait(200)
    ok("deleting cameras hides the button",await t.pg.is_hidden("#camBtn"))
    return t.finish()
