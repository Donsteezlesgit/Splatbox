async def grain(br,site,fx):
    t=await open_page(br,site,"v40grain",w=1000,h=640); ok=t.ok
    await t.pg.evaluate(HASH+";0")
    await t.new_project(); await t.add_ply(fx["tilt"]); await t.ev("closeTool()")
    await t.ev("setMode('render')"); await t.wait(400)
    f=lambda: t.ev("rFrame(320,180,false).then(window.__h)")
    base=await f()
    await t.ev("S.grain=1;GFIX=5"); a=await f(); a2=await f()
    ok("grain changes the picture",a!=base)
    ok("same frame number gives identical grain",a==a2)
    await t.ev("GFIX=6"); b=await f()
    ok("a new frame number gives new grain",a!=b)
    await t.ev("GFIX=5;S.grainSoft=0"); h=await f()
