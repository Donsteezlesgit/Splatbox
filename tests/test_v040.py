    ok("grain rate 3 holds the noise for 3 frames",r1==r2)
    await t.ev("S.grainRate=1;GFIX=-1")
    ok("no shader errors",not [e for e in t.errs if "shader" in str(e).lower()],t.errs)
    # exported frames get different grain
    await t.ev("S.grain=1;S.dur=1;S.rfps=4;S.ralpha=false")
