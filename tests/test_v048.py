async def msgs(br,site,fx):
    t=await open_page(br,site,"v048msgs",w=1300,h=800); ok=t.ok
    await t.new_project(); await t.add_ply(fx["tilt"])
    await t.ev("setStatus('Short one','ok');0"); await t.wait(300)
    b=json.loads(await t.ev("var r=$('toast').getBoundingClientRect(),v=$('gl').getBoundingClientRect();JSON.stringify({l:r.left-v.left,b:v.bottom-r.bottom,w:r.width})"))
    ok("the message sits small in the bottom-left corner",b["l"]<40 and b["b"]<120 and b["w"]<=345,b)
    await t.wait(3500)
    ok("a short message is gone after about 3 s",(await t.ev("$('toast').hidden"))==True)
    await t.ev("setStatus('Bad thing','bad');0"); await t.wait(3500)
    ok("an error is still there at 3.5 s",(await t.ev("$('toast').hidden"))==False)
    await t.wait(3200)
    ok("an error is gone by about 6.5 s",(await t.ev("$('toast').hidden"))==True)
    await t.ev("setStatus('Click me','ok');0"); await t.pg.click("#toast"); await t.wait(100)
    ok("clicking a message dismisses it",(await t.ev("$('toast').hidden"))==True)
    await t.ev("busy(true,'Working…');setStatus('Hello','ok');0"); await t.wait(200)
    g=json.loads(await t.ev("var a=$('busyT').getBoundingClientRect(),b=$('toast').getBoundingClientRect();JSON.stringify({busyTop:a.top,toastBottom:b.bottom})"))
    ok("the Working spinner and a message do not overlap",g["toastBottom"]<=g["busyTop"]+1,g)
    await t.ev("busy(false);0")
    return t.finish()
async def gizmo(br,site,fx):
    t=await open_page(br,site,"v048gizmo",w=1300,h=800); ok=t.ok; pg=t.pg
    await t.new_project(); await t.add_ply(fx["tilt"]); await t.wait(400)
    await t.ev("SEL=null;dirty=true"); await t.wait(250)
    ok("the gizmo button is hidden when nothing is selected",await t.ev("$('gmBtn').hidden")==True)
    await t.ev("SEL=OBJS[0];GM='move';dirty=true"); await t.wait(250)
    ok("it shows when something is selected and says Move",(await t.ev("$('gmBtn').hidden"))==False and (await t.ev("$('gmT').textContent"))=="Move")
    await pg.click("#gmBtn"); await t.wait(100)
    ok("clicking goes Move to Rotate",await t.ev("GM")=="rotate" and (await t.ev("$('gmT').textContent"))=="Rotate")
    await pg.click("#gmBtn"); await t.wait(100); ok("then Scale",await t.ev("GM")=="scale")
    await pg.click("#gmBtn"); await t.wait(100); ok("then back to Move",await t.ev("GM")=="move")
    await pg.mouse.click(5,700); await t.ev("document.activeElement&&document.activeElement.blur()")
    await pg.keyboard.press("KeyT"); await t.wait(100); ok("T cycles forward",await t.ev("GM")=="rotate")
    await pg.keyboard.press("KeyW"); await t.wait(100); ok("W leaves the gizmo alone",await t.ev("GM")=="rotate")
    await pg.keyboard.press("KeyB"); await t.wait(100); ok("B still picks Scale",await t.ev("GM")=="scale")
    await pg.keyboard.press("KeyV"); await t.wait(100); ok("V still picks Rotate",await t.ev("GM")=="rotate")
    await t.ev("addCamera();leaveThru()"); await t.wait(300)
    await t.ev("GM='move';dirty=true"); await pg.mouse.click(5,700); await t.ev("document.activeElement&&document.activeElement.blur()")
    await pg.keyboard.press("KeyT"); await t.wait(100); await pg.keyboard.press("KeyT"); await t.wait(100)
    ok("a camera skips Scale (Move, Rotate, Move)",await t.ev("GM")=="move")
    await t.ev("var i=document.createElement('input');i.id='tmpIn';document.body.appendChild(i);i.focus();0")
    await pg.keyboard.press("KeyT"); await t.wait(100)
    ok("typing T in a box does not change the gizmo",await t.ev("GM")=="move")
    await t.ev("$('tmpIn').remove();0")
    await pg.screenshot(path="/tmp/shots/gizmo_btn.png")
    return t.finish()
async def savestate(br,site,fx):
    t=await open_page(br,site,"v048save",w=1300,h=800); ok=t.ok; pg=t.pg
    await t.new_project(); await t.add_ply(fx["tilt"]); await t.wait(1500)
    ok("a saved project shows no unsaved mark",(await t.ev("$('saveBtn').dataset.sv"))=="saved")
    await t.ev("S.fog=0.3;saveSoon();0"); await t.wait(150)
    ok("a change shows 'unsaved' straight away",(await t.ev("$('saveBtn').dataset.sv"))=="pending" and "Unsaved" in await t.ev("$('saveBtn').getAttribute('aria-label')"))
    await t.wait(1800)
    ok("and goes back to saved after the autosave",(await t.ev("$('saveBtn').dataset.sv"))=="saved")
    # folder disconnected: banner + save mark, then it clears when the folder is back
    ok("no folder warning normally",(await t.ev("$('folderWarn').hidden"))==True)
    await t.ev("FOLD.h={name:'Projects'};FOLD.ok=false;FOLD.lapsed=true;0"); await t.wait(300)
    ok("the banner shows when the folder is disconnected",(await t.ev("$('folderWarn').hidden"))==False and "Reconnect" in await t.pg.inner_text("#fwBtn"))
    ok("the save button says the folder is disconnected",(await t.ev("$('saveBtn').dataset.sv"))=="folder")
    await pg.screenshot(path="/tmp/shots/folder_warn.png")
    await t.ev("window._r=0;fsHeal=function(){window._r++;FOLD.ok=true;FOLD.lapsed=false;return Promise.resolve(true)};0")
    await pg.click("#fwBtn"); await t.wait(300)
    ok("Reconnect asks for the folder back",(await t.ev("window._r"))==1)
    ok("the banner goes away once it is back",(await t.ev("$('folderWarn').hidden"))==True and (await t.ev("$('saveBtn').dataset.sv"))=="saved")
    await t.ev("FOLD.h=null;FOLD.ok=false;FOLD.lapsed=false;0")
    return t.finish()
async def undodel(br,site,fx):
    t=await open_page(br,site,"v048undo",w=1300,h=800); ok=t.ok; pg=t.pg
    await t.wait(800)
    await t.ev("setStatus('Home message','ok');0"); await t.wait(200)
    r=json.loads(await t.ev("var r=$('toastH').getBoundingClientRect();JSON.stringify({w:r.width,h:r.height,l:r.left,b:innerHeight-r.bottom})"))
    ok("messages now show on the Home screen too",r["w"]>40 and r["h"]>10 and r["l"]<40,r)
    await t.new_project(); await t.ev("goHome()"); await t.wait(700)
    n0=await t.ev("document.querySelectorAll('#grid .card:not(.new)').length")
    ok("there is a project on Home",n0>=1,n0)
    await pg.click("#grid .card:not(.new) .more >> nth=0"); await t.wait(200)
    await pg.click(".menu .danger"); await t.wait(500)
    n1=await t.ev("document.querySelectorAll('#grid .card:not(.new)').length")
    ok("Delete takes it off the list at once, no 'tap again'",n1==n0-1,[n0,n1])
    ok("a message offers Undo",(await t.ev("$('toastH').hidden"))==False and "Undo" in await pg.inner_text("#toastH"))
    ok("it is not really deleted yet",(await t.ev("Object.keys(PEND).length"))==1)
    await pg.screenshot(path="/tmp/shots/undo_delete.png")
    await pg.click("#toastH .tact"); await t.wait(600)
    n2=await t.ev("document.querySelectorAll('#grid .card:not(.new)').length")
    ok("Undo brings the project back",n2==n0 and (await t.ev("Object.keys(PEND).length"))==0,[n0,n2])
    # and the real delete happens if you leave it
    await pg.click("#grid .card:not(.new) .more >> nth=0"); await t.wait(200)
    await pg.click(".menu .danger"); await t.wait(300)
    await t.ev("pendFlush(Object.keys(PEND)[0])"); await t.wait(700)
    n3=await t.ev("document.querySelectorAll('#grid .card:not(.new)').length")
    ok("left alone, it is really deleted",n3==n0-1 and (await t.ev("Object.keys(PEND).length"))==0,[n0,n3])
    return t.finish()
